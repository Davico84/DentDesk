UPDATE memberships SET role = 'DENTIST' WHERE role = 'USER';

ALTER TABLE memberships
    ADD CONSTRAINT ck_memberships_role CHECK (role IN ('ADMIN', 'DENTIST', 'RECEPTIONIST'));

CREATE TABLE invitations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    invited_by      BIGINT NOT NULL REFERENCES users (id),
    email           VARCHAR(254) NOT NULL,
    token_hash      VARCHAR(64) NOT NULL UNIQUE,
    role            VARCHAR(20) NOT NULL CHECK (role IN ('DENTIST', 'RECEPTIONIST')),
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED')),
    expires_at      TIMESTAMPTZ NOT NULL,
    accepted_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_invitations_org_status ON invitations (organization_id, status);
CREATE INDEX ix_invitations_email ON invitations (lower(email), status);
