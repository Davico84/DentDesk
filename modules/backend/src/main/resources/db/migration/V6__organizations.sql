-- Capacidad: multi-tenancy — modelo Identidad(User) / Organización / Membresía.
-- El `User` (identidad global) ya existe. Aquí se añaden el tenant (Organization),
-- su configuración 1:1 y la tabla puente (Membership) que lleva el rol.

-- 1) Organizaciones (el tenant que se aísla)
CREATE TABLE organizations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    slug       VARCHAR(140) NOT NULL,
    type       VARCHAR(30)  NOT NULL DEFAULT 'CLINIC',
    status     VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_organizations_slug ON organizations (slug);

-- 2) Configuración 1:1 de la organización (punto de extensión: TZ / locale / moneda)
CREATE TABLE organization_settings (
    organization_id BIGINT PRIMARY KEY REFERENCES organizations (id) ON DELETE CASCADE,
    timezone        VARCHAR(64) NOT NULL DEFAULT 'America/Lima',
    locale          VARCHAR(10) NOT NULL DEFAULT 'es-PE',
    currency        VARCHAR(3)  NOT NULL DEFAULT 'PEN'
);

-- 3) Membresías (puente identidad↔organización; aquí vive el rol)
CREATE TABLE memberships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    organization_id BIGINT      NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    role            VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- El único (user_id, organization_id) sirve las consultas que lideran por user_id
-- (incluida la policy RLS de identidad); falta el índice que lidera por organización.
CREATE UNIQUE INDEX ux_memberships_user_org ON memberships (user_id, organization_id);
CREATE INDEX ix_memberships_org ON memberships (organization_id);

-- 4) La identidad gana su propio ciclo de vida (independiente del de la membresía)
ALTER TABLE users ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';

-- 5) Backfill idempotente (greenfield: normalmente `users` está vacía y no hace nada).
--    Estrategia: una organización propia por cada usuario existente, del que queda
--    como ADMIN. No se fusionan identidades distintas en un mismo tenant; y así
--    ninguna organización nace sin administrador (invariante del modelo).
INSERT INTO organizations (name, slug, type, status)
SELECT 'Clínica ' || u.id, 'clinica-' || u.id, 'CLINIC', 'ACTIVE'
FROM users u;

INSERT INTO organization_settings (organization_id)
SELECT o.id FROM organizations o;

INSERT INTO memberships (user_id, organization_id, role, status)
SELECT u.id, o.id, 'ADMIN', 'ACTIVE'
FROM users u
JOIN organizations o ON o.slug = 'clinica-' || u.id;

-- 6) El rol deja de ser atributo de la identidad (ya migrado a la membresía)
ALTER TABLE users DROP COLUMN role;

-- 7) Menor privilegio: conceder DML al rol de aplicación (no-owner) si existe.
--    En despliegue existen dos roles (admin=Flyway/owner, app=runtime/DML). En local
--    con un único usuario, este bloque simplemente no hace nada. Ver scripts/db-roles.sql.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'odontorisas_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO odontorisas_app';
        EXECUTE 'GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO odontorisas_app';
        -- Que las tablas futuras (capacidades de negocio) hereden el GRANT sin repetirlo.
        EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO odontorisas_app';
        EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO odontorisas_app';
    END IF;
END $$;
